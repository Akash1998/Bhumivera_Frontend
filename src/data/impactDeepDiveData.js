// Helper to look up any project by any ID, slug, poster ID, or category
export const findProjectById = idOrSlug => {
  if (!idOrSlug) return IMPACT_PROJECTS[0];
  const query = String(idOrSlug).toLowerCase().trim();

  // Find exact id or slug or aliases
  const match = IMPACT_PROJECTS.find(
    p =>
      p.id.toLowerCase() === query ||
      p.slug.toLowerCase() === query ||
      (p.aliases && p.aliases.some(a => a.toLowerCase() === query)) ||
      (p.posterId && p.posterId.toLowerCase() === query)
  );

  return match || IMPACT_PROJECTS[0];
};
